def main():
    if not DB_PATH.exists():
        raise SystemExit(f"Database not found: {DB_PATH}")

    con = sqlite3.connect(DB_PATH)
    cur = con.cursor()

    for sid, name_ar, name_plain in CANONICAL_SURAHS:
        cur.execute(
            "UPDATE surahs SET name_ar = ?, name_ar_plain = ? WHERE id = ?",
            (name_ar, name_plain, sid),
        )

    con.commit()
    con.close()
    print("Successfully updated 114 surah names in quran.db!")

    # Bump version text to force asset sync
    if VERSION_PATH.exists():
        current = VERSION_PATH.read_text(encoding="utf-8").strip()
        next_version = str(int(current) + 1) if current.isdigit() else "v_surah_names_fix"
        VERSION_PATH.write_text(next_version, encoding="utf-8")
        print(f"Bumped {VERSION_PATH.name}: {current} -> {next_version}")

if __name__ == "__main__":
    main()
