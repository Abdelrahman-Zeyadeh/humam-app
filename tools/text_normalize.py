#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
تطبيع نص عربي للبحث (حذف تشكيل + توحيد حروف متشابهة رسماً) — مشترك بين
`build_quran_db.py` و`build_hadith_db.py`. **يجب** تطبيق نفس المنطق على
مدخل المستخدم وقت البحث (`arabic_normalizer.dart` بطرف Dart).
"""
from __future__ import annotations

import re

_DIACRITICS = re.compile(
    "[" + "".join(
        chr(c) for c in list(range(0x0610, 0x061B)) + list(range(0x064B, 0x0654))
        + list(range(0x0656, 0x065F + 1)) + list(range(0x06D6, 0x06ED + 1))
        + [0x0670]
    ) + "]"
)


def normalize_search_text(text: str) -> str:
    t = _DIACRITICS.sub("", text)
    t = t.replace("ـ", "")  # تطويل
    t = re.sub("[آأإٱ]", "ا", t)  # أإآٱ -> ا
    t = t.replace("ة", "ه")  # ة -> ه
    t = t.replace("ى", "ي")  # ى -> ي
    return t


def strip_diacritics(text: str) -> str:
    return _DIACRITICS.sub("", text).replace("ـ", "")


def strip_diacritics_for_display(text: str) -> str:
    """نسخة آمنة للعرض من [strip_diacritics] — **تستبدل** الألف الخنجرية
    (U+0670) بحرف بدل حذفها كباقي التشكيل. الألف الخنجرية بالرسم العثماني
    تمثّل حرفاً فعلياً محذوفاً رسماً (مدّة الألف)، لا مجرد حركة نطق —
    حذفها كباقي التشكيل (كما كان يحدث بـ[strip_diacritics] قبل هذه
    الدالة) يُسقط حرفاً فعلياً من الكلمة، لا مجرد تشكيلها. مثال حقيقي
    (بلاغ صاحب المشروع "اسم السورة مكتوب غلط"): "اٰلِ عِمْرٰنَ" (آل عمران)
    كانت تصير "ال عمرن" — ناقصة الألف بالكلمتين معاً.

    القاعدة: ألف + ألف خنجرية متتاليتان -> "آ" (نفس مخرج المدّة)، ألف
    خنجرية متبوعة بياء -> "ى" (ألف مقصورة — راجع بلاغ صاحب المشروع
    "الشورى صارت الشوراي، الأعلى صارت الاعلاي، الضحى صارت الضحاي": بلا
    هذه القاعدة كانت الكلمات المنتهية بألف مقصورة بالرسم العثماني
    (يُكتَب مدّها الأخير بألف خنجرية+ياء لا ألف مقصورة صريحة) تتحوّل خطأً
    لـ"اي" بدل "ى")، وألف خنجرية منفردة غير هاتين الحالتين -> "ا" عادية.
    تُستخدَم فقط لحقول عرض مُشتقّة مثل `name_ar_plain` — **لا** لنص الآية
    القرآني نفسه (`text_uthmani` يبقى بالرسم الأصلي بلا أي تعديل، بأي
    مكان بالكود).

    **استثناء لا تحلّه هذه الدالة إطلاقاً بذاتها:** أسماء السور
    التي رسمها العثماني يضيف ألفاً خنجرية لحروف مقطَّعة لا تُنطَق ألفاً
    بالتسمية المتعارفة (طٰهٰ -> "طه" لا "طاها"، يٰس -> "يس" لا "ياس") —
    راجع `_PLAIN_NAME_OVERRIDES` بـ`build_quran_db.py`، استثناء صريح بعد
    استدعاء هذه الدالة لا تعميم هون (قاعدة عامة أي لفظ عادي محتاجها فعلاً،
    الاستثناء يخص هذين الاسمين تحديداً)."""
    text = text.replace("اٰ", "آ")
    text = text.replace("ٰي", "ى")
    text = text.replace("ٰ", "ا")
    return strip_diacritics(text)
