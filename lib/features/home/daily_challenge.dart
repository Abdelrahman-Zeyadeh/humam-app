/// قائمة التحديات الشخصية اليومية — مهام صغيرة إضافية (لا تعوّض الورد
/// الثابت، مجرّد دفعة إضافية اختيارية) تغطي أغلب أقسام التطبيق كي لا
/// يقتصر التحدي على قسم واحد فقط.
const List<String> _kDailyChallenges = [
  'اقرأ صفحة إضافية عن وردك المعتاد اليوم',
  'احفظ آية جديدة أو راجع صفحة من محفوظاتك',
  'استمع لـ ١٠ دقائق تلاوة من قارئ جديد لم تجرّبه',
  'اقرأ سورة قصيرة كاملة من المصحف الآن',
  'أرسل آية أو حديثاً أعجبك اليوم لصديق',
  'أتمّ أذكار الصباح أو المساء كاملة بلا تسرّع',
  'راجع معنى آية بالتفسير المبسّط قبل أن تكمل قراءتك',
  'صلِّ ركعتين تطوّعاً بغير أوقات النهي',
  'ادعُ لوالديك بدعاء خاص اليوم',
  'استغفر الله ١٠٠ مرة اليوم',
  'تعلّم حكماً تجويدياً جديداً من قسم "أدواتي"',
  'اقرأ حديث اليوم وتأمّل بمعناه قليلاً قبل المتابعة',
];

/// يختار تحدي اليوم بشكل **ثابت** طوال نفس اليوم التقويمي (لا عشوائي حقيقي
/// يتغيّر بكل إعادة بناء) — نفس تاريخ اليوم كـ"بذرة" بسيطة (باقي القسمة
/// على عدد التحديات)، فيتغيّر التحدي المعروض تلقائياً كل يوم بلا أي تخزين
/// إضافي يحفظ "تحدي اليوم" صراحة.
String dailyChallengeTextFor(DateTime day) {
  final seed = day.year * 372 + day.month * 31 + day.day; // فريد لكل يوم تقويمي
  return _kDailyChallenges[seed % _kDailyChallenges.length];
}
