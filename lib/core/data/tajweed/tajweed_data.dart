/// نموذج حكم تجويدي
class TajweedRule {
  final String id;
  final String title;
  final String category;
  final String definition;
  final String letters;
  final String explanation;
  final String? poetryProof; // شاهد من تحفة الأطفال أو الجزرية
  final List<TajweedExample> examples;
  final String colorHex; // لون التمييز الاصطلاحي

  const TajweedRule({
    required this.id,
    required this.title,
    required this.category,
    required this.definition,
    required this.letters,
    required this.explanation,
    this.poetryProof,
    required this.examples,
    this.colorHex = '#C9A24B',
  });
}

/// مثال قرآني تطبيقي للحكم
class TajweedExample {
  final String surah;
  final int ayah;
  final String versePart;
  final String highlightedWord;
  final String note;

  const TajweedExample({
    required this.surah,
    required this.ayah,
    required this.versePart,
    required this.highlightedWord,
    required this.note,
  });
}

/// علامة ضبط ووقف في المصحف
class QuranStopMark {
  final String symbol;
  final String name;
  final String meaning;
  final String rule;
  final String example;

  const QuranStopMark({
    required this.symbol,
    required this.name,
    required this.meaning,
    required this.rule,
    required this.example,
  });
}

