/// البحث في المواضيع حسب الكلمة المفتاحية
List<QuranTopic> searchQuranTopics(String query) {
  final clean = normalizeArabicSearch(query.trim());
  if (clean.isEmpty) return const [];
  
  return kQuranTopics.where((topic) {
    if (normalizeArabicSearch(topic.title).contains(clean)) return true;
    if (normalizeArabicSearch(topic.description).contains(clean)) return true;
    return topic.keywords.any((kw) => normalizeArabicSearch(kw).contains(clean) || clean.contains(normalizeArabicSearch(kw)));
  }).toList();
}
