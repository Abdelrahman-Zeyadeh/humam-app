  /// جلب اسم اليوم حسب رقم اليوم في السنة
  static NameOfAllah nameOfTheDay() {
    final now = DateTime.now();
    final dayOfYear = now.difference(DateTime(now.year, 1, 1)).inDays;
    return items[dayOfYear % items.length];
  }

  /// بحث في الأسماء حسب النص
  static List<NameOfAllah> search(String query) {
    if (query.trim().isEmpty) return items;
    final q = query.trim().replaceAll('ال', '').replaceAll(RegExp(r'[\u064B-\u065F\u0670]'), '');
    return items.where((name) {
      final cleanName = name.name.replaceAll('ال', '').replaceAll(RegExp(r'[\u064B-\u065F\u0670]'), '');
      return cleanName.contains(q) || name.meaning.contains(query) || name.category.contains(query);
    }).toList();
  }
