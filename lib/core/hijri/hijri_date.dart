/// لا خطأ بالتنفيذ. لا واجهة لتعديل الإزاحة ±يوم يدوياً بعد.
String todayHijriArabic() {
  final cal = HijriCalendar.now();
  HijriCalendar.language = 'ar';
  return '${cal.hDay} ${cal.getLongMonthName()} ${cal.hYear}هـ';
}
